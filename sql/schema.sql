-- =====================================================================
--  Bodega · Esquema de base de datos (PostgreSQL)
--  Funciona en Supabase y en el modo demo (PGlite, dentro del navegador).
--
--  Idea central: el stock NUNCA se escribe a mano.
--    · Cada ingreso crea un LOTE (cantidad + fecha de vencimiento).
--    · Toda salida, entrega de kit, devolución o ajuste se guarda como
--      MOVIMIENTOS sobre lotes (negativo = sale, positivo = vuelve).
--    · Stock de un lote = cantidad ingresada + suma de sus movimientos.
--  Las operaciones que mueven stock son funciones (RPC) transaccionales:
--  o se aplica todo o nada, y bloquean los lotes para evitar descuadres
--  si dos personas registran al mismo tiempo.
-- =====================================================================

-- ---------------------------------------------------------------- tablas
create table if not exists configuracion (
  clave text primary key,
  valor text
);

create table if not exists categorias (
  id bigint generated by default as identity primary key,
  nombre text not null unique check (length(trim(nombre)) > 0),
  creado_en timestamptz not null default now()
);

create table if not exists unidades (
  id bigint generated by default as identity primary key,
  nombre text not null unique check (length(trim(nombre)) > 0),
  abreviatura text,
  creado_en timestamptz not null default now()
);

create table if not exists insumos (
  id bigint generated by default as identity primary key,
  codigo text not null unique check (length(trim(codigo)) > 0),
  nombre text not null check (length(trim(nombre)) > 0),
  categoria_id bigint references categorias(id) on delete restrict,
  unidad_id bigint references unidades(id) on delete restrict,
  stock_minimo integer not null default 0 check (stock_minimo >= 0),
  reutilizable boolean not null default false,   -- ¿vuelve al stock al devolver un kit?
  activo boolean not null default true,
  notas text,
  creado_en timestamptz not null default now()
);

-- Cada ingreso de mercadería es un lote con su propio vencimiento
create table if not exists lotes (
  id bigint generated by default as identity primary key,
  insumo_id bigint not null references insumos(id) on delete restrict,
  fecha_ingreso date not null,
  cantidad integer not null check (cantidad > 0),
  vence date,
  codigo_lote text,
  proveedor text,
  documento text,
  nota text,
  creado_en timestamptz not null default now()
);

-- Plantillas de kit (receta: qué insumos y cuántos)
create table if not exists kits (
  id bigint generated by default as identity primary key,
  codigo text not null unique check (length(trim(codigo)) > 0),
  nombre text not null check (length(trim(nombre)) > 0),
  descripcion text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists kit_items (
  kit_id bigint not null references kits(id) on delete cascade,
  insumo_id bigint not null references insumos(id) on delete restrict,
  cantidad integer not null check (cantidad > 0),
  primary key (kit_id, insumo_id)
);

-- Kits armados y entregados a una persona (préstamo)
create table if not exists entregas (
  id bigint generated by default as identity primary key,
  kit_id bigint references kits(id) on delete set null,
  kit_nombre text not null,
  fecha_entrega date not null,
  persona text not null check (length(trim(persona)) > 0),
  destino text,
  responsable text,
  nota text,
  estado text not null default 'entregado' check (estado in ('entregado', 'devuelto')),
  fecha_devolucion date,
  recibido_por text,
  nota_devolucion text,
  creado_en timestamptz not null default now()
);

create table if not exists entrega_items (
  id bigint generated by default as identity primary key,
  entrega_id bigint not null references entregas(id) on delete cascade,
  insumo_id bigint not null references insumos(id) on delete restrict,
  cantidad integer not null check (cantidad > 0),
  devuelto integer check (devuelto >= 0),       -- vuelve al stock
  descartado integer check (descartado >= 0)    -- usado / desechado, no vuelve
);

-- Encabezado de cada operación que mueve stock
create table if not exists operaciones (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('salida', 'baja', 'ajuste', 'entrega_kit', 'devolucion_kit')),
  fecha date not null,
  insumo_id bigint references insumos(id) on delete restrict,
  entrega_id bigint references entregas(id) on delete cascade,
  motivo text,
  destino text,
  persona text,
  nota text,
  creado_en timestamptz not null default now()
);

-- Detalle por lote (el "libro mayor" del inventario)
create table if not exists movimientos (
  id bigint generated by default as identity primary key,
  operacion_id bigint not null references operaciones(id) on delete cascade,
  lote_id bigint not null references lotes(id) on delete restrict,
  cantidad integer not null check (cantidad <> 0)
);

create index if not exists idx_lotes_insumo on lotes(insumo_id);
create index if not exists idx_mov_lote on movimientos(lote_id);
create index if not exists idx_mov_operacion on movimientos(operacion_id);
create index if not exists idx_oper_entrega on operaciones(entrega_id);
create index if not exists idx_eitems_entrega on entrega_items(entrega_id);

-- ----------------------------------------------------------------- vistas
create or replace view v_lotes as
select l.id, l.insumo_id, l.fecha_ingreso, l.cantidad, l.vence, l.codigo_lote, l.proveedor,
       l.documento, l.nota, l.creado_en,
       (l.cantidad + coalesce(m.delta, 0))::integer as disponible
from lotes l
left join (select lote_id, sum(cantidad) as delta from movimientos group by lote_id) m on m.lote_id = l.id;

-- -------------------------------------------------------------- funciones
-- Stock actual de un lote
create or replace function _disponible(p_lote bigint) returns integer
language sql stable as $$
  select (l.cantidad + coalesce((select sum(m.cantidad) from movimientos m where m.lote_id = l.id), 0))::integer
  from lotes l where l.id = p_lote
$$;

-- Descuenta p_cantidad de un insumo, lote por lote, en orden FEFO
-- (primero el que vence antes). Lanza error si no alcanza.
create or replace function _descontar_fefo(
  p_op bigint, p_insumo bigint, p_cantidad integer, p_fecha date,
  p_excluir_vencidos boolean, p_solo_vencidos boolean, p_lote bigint
) returns void
language plpgsql as $$
declare
  r record;
  v_need integer := p_cantidad;
  v_take integer;
  v_nombre text;
begin
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'La cantidad debe ser mayor a 0';
  end if;
  -- bloquear los lotes del insumo mientras se calcula
  perform 1 from lotes where insumo_id = p_insumo for update;

  for r in
    select l.id, _disponible(l.id) as disp
    from lotes l
    where l.insumo_id = p_insumo
      and l.fecha_ingreso <= p_fecha
      and (p_lote is null or l.id = p_lote)
      and (not p_excluir_vencidos or l.vence is null or l.vence >= p_fecha)
      and (not p_solo_vencidos or (l.vence is not null and l.vence < p_fecha))
    order by coalesce(l.vence, date '9999-12-31'), l.fecha_ingreso, l.id
  loop
    exit when v_need <= 0;
    if r.disp > 0 then
      v_take := least(v_need, r.disp);
      insert into movimientos (operacion_id, lote_id, cantidad) values (p_op, r.id, -v_take);
      v_need := v_need - v_take;
    end if;
  end loop;

  if v_need > 0 then
    select nombre into v_nombre from insumos where id = p_insumo;
    raise exception 'Stock insuficiente de "%": faltan % para completar %', coalesce(v_nombre, '?'), v_need, p_cantidad;
  end if;
end $$;

-- Verifica que ningún lote quede con stock negativo
create or replace function _verificar_lotes(p_lotes bigint[]) returns void
language plpgsql as $$
declare v_id bigint;
begin
  select id into v_id from v_lotes where id = any(p_lotes) and disponible < 0 limit 1;
  if v_id is not null then
    raise exception 'La operación dejaría stock negativo en un lote (ya se usaron esas unidades después)';
  end if;
end $$;

-- ---------------------------------------------------------------- ingresos
create or replace function registrar_ingreso(
  p_insumo bigint, p_fecha date, p_cantidad integer,
  p_vence date default null, p_codigo_lote text default null, p_proveedor text default null,
  p_documento text default null, p_nota text default null
) returns bigint
language plpgsql as $$
declare v_id bigint;
begin
  if p_insumo is null then raise exception 'Selecciona un insumo'; end if;
  if p_fecha is null then raise exception 'Indica la fecha de ingreso'; end if;
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor a 0'; end if;
  if p_vence is not null and p_vence < p_fecha - 3650 then raise exception 'Fecha de vencimiento inválida'; end if;
  insert into lotes (insumo_id, fecha_ingreso, cantidad, vence, codigo_lote, proveedor, documento, nota)
  values (p_insumo, p_fecha, p_cantidad, p_vence, nullif(trim(p_codigo_lote), ''), nullif(trim(p_proveedor), ''),
          nullif(trim(p_documento), ''), nullif(trim(p_nota), ''))
  returning id into v_id;
  return v_id;
end $$;

-- ----------------------------------------------------------------- salidas
-- p_motivo: 'Despacho' (no usa vencidos), 'Baja por vencimiento' (solo vencidos),
--           'Merma / daño', u otro texto. p_lote fuerza un lote específico.
create or replace function registrar_salida(
  p_insumo bigint, p_cantidad integer, p_fecha date,
  p_motivo text default 'Despacho', p_destino text default null, p_persona text default null,
  p_nota text default null, p_lote bigint default null
) returns bigint
language plpgsql as $$
declare
  v_op bigint;
  v_motivo text := coalesce(nullif(trim(p_motivo), ''), 'Despacho');
begin
  if p_insumo is null then raise exception 'Selecciona un insumo'; end if;
  if p_fecha is null then raise exception 'Indica la fecha'; end if;
  insert into operaciones (tipo, fecha, insumo_id, motivo, destino, persona, nota)
  values (case when v_motivo = 'Despacho' then 'salida' else 'baja' end, p_fecha, p_insumo, v_motivo,
          nullif(trim(p_destino), ''), nullif(trim(p_persona), ''), nullif(trim(p_nota), ''))
  returning id into v_op;
  perform _descontar_fefo(v_op, p_insumo, p_cantidad, p_fecha,
                          p_lote is null and v_motivo = 'Despacho',
                          p_lote is null and v_motivo = 'Baja por vencimiento',
                          p_lote);
  return v_op;
end $$;

-- ------------------------------------------------------------------ ajustes
-- Conteo físico: deja el lote con p_contado unidades y registra la diferencia
create or replace function ajustar_stock(
  p_lote bigint, p_contado integer, p_fecha date,
  p_motivo text default 'Conteo físico', p_nota text default null
) returns bigint
language plpgsql as $$
declare
  v_insumo bigint;
  v_disp integer;
  v_op bigint;
begin
  if p_contado is null or p_contado < 0 then raise exception 'La cantidad contada debe ser 0 o más'; end if;
  select insumo_id into v_insumo from lotes where id = p_lote for update;
  if v_insumo is null then raise exception 'Lote no encontrado'; end if;
  v_disp := _disponible(p_lote);
  if p_contado = v_disp then raise exception 'No hay diferencia: el sistema ya registra % unidades', v_disp; end if;
  insert into operaciones (tipo, fecha, insumo_id, motivo, nota)
  values ('ajuste', p_fecha, v_insumo, coalesce(nullif(trim(p_motivo), ''), 'Conteo físico'), nullif(trim(p_nota), ''))
  returning id into v_op;
  insert into movimientos (operacion_id, lote_id, cantidad) values (v_op, p_lote, p_contado - v_disp);
  return v_op;
end $$;

-- Anula una salida, baja o ajuste (devuelve el stock a sus lotes)
create or replace function anular_operacion(p_op bigint) returns void
language plpgsql as $$
declare
  v_tipo text;
  v_lotes bigint[];
begin
  select tipo into v_tipo from operaciones where id = p_op;
  if v_tipo is null then raise exception 'Operación no encontrada'; end if;
  if v_tipo not in ('salida', 'baja', 'ajuste') then
    raise exception 'Las entregas y devoluciones de kits se anulan desde la sección Kits';
  end if;
  select array_agg(lote_id) into v_lotes from movimientos where operacion_id = p_op;
  delete from operaciones where id = p_op;
  perform _verificar_lotes(coalesce(v_lotes, '{}'));
end $$;

-- --------------------------------------------------------------------- kits
-- Crea o actualiza una plantilla de kit con sus insumos.
-- p_items: [{"insumo_id": 1, "cantidad": 2}, ...]
create or replace function guardar_kit(
  p_id bigint, p_codigo text, p_nombre text, p_descripcion text, p_items jsonb, p_activo boolean default true
) returns bigint
language plpgsql as $$
declare v_id bigint := p_id;
begin
  if coalesce(trim(p_codigo), '') = '' or coalesce(trim(p_nombre), '') = '' then
    raise exception 'El kit necesita código y nombre';
  end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Agrega al menos un insumo al kit';
  end if;
  if v_id is null then
    insert into kits (codigo, nombre, descripcion, activo)
    values (upper(trim(p_codigo)), trim(p_nombre), nullif(trim(p_descripcion), ''), coalesce(p_activo, true))
    returning id into v_id;
  else
    update kits set codigo = upper(trim(p_codigo)), nombre = trim(p_nombre),
                    descripcion = nullif(trim(p_descripcion), ''), activo = coalesce(p_activo, true)
    where id = v_id;
    if not found then raise exception 'Kit no encontrado'; end if;
    delete from kit_items where kit_id = v_id;
  end if;
  insert into kit_items (kit_id, insumo_id, cantidad)
  select v_id, (e ->> 'insumo_id')::bigint, sum((e ->> 'cantidad')::integer)
  from jsonb_array_elements(p_items) e
  where (e ->> 'insumo_id') is not null and coalesce((e ->> 'cantidad')::integer, 0) > 0
  group by (e ->> 'insumo_id')::bigint;
  if not exists (select 1 from kit_items where kit_id = v_id) then
    raise exception 'Agrega al menos un insumo con cantidad mayor a 0';
  end if;
  return v_id;
end $$;

-- Arma y entrega un kit a una persona. Descuenta cada insumo (FEFO, sin vencidos).
-- p_items permite ajustar el contenido al momento de armarlo.
create or replace function entregar_kit(
  p_kit bigint, p_fecha date, p_persona text, p_items jsonb,
  p_destino text default null, p_responsable text default null, p_nota text default null
) returns bigint
language plpgsql as $$
declare
  v_ent bigint;
  v_op bigint;
  r record;
begin
  if coalesce(trim(p_persona), '') = '' then raise exception 'Indica a quién se entrega el kit'; end if;
  if p_fecha is null then raise exception 'Indica la fecha de entrega'; end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then raise exception 'El kit no tiene insumos'; end if;

  insert into entregas (kit_id, kit_nombre, fecha_entrega, persona, destino, responsable, nota)
  values (p_kit, coalesce((select nombre from kits where id = p_kit), 'Kit personalizado'), p_fecha, trim(p_persona),
          nullif(trim(p_destino), ''), nullif(trim(p_responsable), ''), nullif(trim(p_nota), ''))
  returning id into v_ent;

  insert into operaciones (tipo, fecha, entrega_id, destino, persona, nota)
  values ('entrega_kit', p_fecha, v_ent, nullif(trim(p_destino), ''), trim(p_persona), nullif(trim(p_nota), ''))
  returning id into v_op;

  for r in
    select (e ->> 'insumo_id')::bigint as insumo_id, sum((e ->> 'cantidad')::integer)::integer as cantidad
    from jsonb_array_elements(p_items) e
    where (e ->> 'insumo_id') is not null
    group by (e ->> 'insumo_id')::bigint
  loop
    if r.cantidad > 0 then
      insert into entrega_items (entrega_id, insumo_id, cantidad) values (v_ent, r.insumo_id, r.cantidad);
      perform _descontar_fefo(v_op, r.insumo_id, r.cantidad, p_fecha, true, false, null);
    end if;
  end loop;

  if not exists (select 1 from entrega_items where entrega_id = v_ent) then
    raise exception 'El kit no tiene insumos con cantidad mayor a 0';
  end if;
  return v_ent;
end $$;

-- Registra la devolución de un kit.
-- p_items: [{"id": <entrega_item_id>, "devuelto": n, "descartado": m}, ...]
-- devuelto + descartado debe ser igual a lo entregado de cada insumo.
-- Lo devuelto vuelve a los mismos lotes de los que salió.
create or replace function devolver_kit(
  p_entrega bigint, p_fecha date, p_items jsonb,
  p_recibido_por text default null, p_nota text default null
) returns bigint
language plpgsql as $$
declare
  v_e entregas%rowtype;
  v_op_ent bigint;
  v_op bigint;
  it record;
  m record;
  v_dev integer;
  v_desc integer;
  v_need integer;
  v_put integer;
  v_nombre text;
begin
  select * into v_e from entregas where id = p_entrega for update;
  if v_e.id is null then raise exception 'Entrega no encontrada'; end if;
  if v_e.estado <> 'entregado' then raise exception 'Este kit ya fue devuelto'; end if;
  if p_fecha is null then raise exception 'Indica la fecha de devolución'; end if;
  if p_fecha < v_e.fecha_entrega then raise exception 'La devolución no puede ser anterior a la entrega'; end if;

  select id into v_op_ent from operaciones where entrega_id = p_entrega and tipo = 'entrega_kit';

  insert into operaciones (tipo, fecha, entrega_id, persona, nota)
  values ('devolucion_kit', p_fecha, p_entrega, v_e.persona, nullif(trim(p_nota), ''))
  returning id into v_op;

  for it in select * from entrega_items where entrega_id = p_entrega order by id loop
    select coalesce((e ->> 'devuelto')::integer, 0), coalesce((e ->> 'descartado')::integer, 0)
      into v_dev, v_desc
    from jsonb_array_elements(p_items) e
    where (e ->> 'id')::bigint = it.id;
    select nombre into v_nombre from insumos where id = it.insumo_id;
    if v_dev is null then raise exception 'Falta indicar qué pasa con "%"', v_nombre; end if;
    if v_dev < 0 or v_desc < 0 or v_dev + v_desc <> it.cantidad then
      raise exception 'En "%": lo devuelto más lo desechado debe sumar %', v_nombre, it.cantidad;
    end if;
    update entrega_items set devuelto = v_dev, descartado = v_desc where id = it.id;

    -- restituir lo devuelto en los lotes de origen
    v_need := v_dev;
    for m in
      select mv.lote_id, (-sum(mv.cantidad))::integer as tomado
      from movimientos mv join lotes l on l.id = mv.lote_id
      where mv.operacion_id = v_op_ent and l.insumo_id = it.insumo_id
      group by mv.lote_id, l.vence, l.fecha_ingreso
      order by coalesce(l.vence, date '9999-12-31'), l.fecha_ingreso, mv.lote_id
    loop
      exit when v_need <= 0;
      v_put := least(v_need, m.tomado);
      if v_put > 0 then
        insert into movimientos (operacion_id, lote_id, cantidad) values (v_op, m.lote_id, v_put);
        v_need := v_need - v_put;
      end if;
    end loop;
    v_dev := null;
    v_desc := null;
  end loop;

  update entregas set estado = 'devuelto', fecha_devolucion = p_fecha,
         recibido_por = nullif(trim(p_recibido_por), ''), nota_devolucion = nullif(trim(p_nota), '')
  where id = p_entrega;
  return v_op;
end $$;

-- Deshace una devolución (el kit vuelve a quedar "entregado")
create or replace function revertir_devolucion(p_entrega bigint) returns void
language plpgsql as $$
declare v_lotes bigint[];
begin
  if not exists (select 1 from entregas where id = p_entrega and estado = 'devuelto') then
    raise exception 'La entrega no está devuelta';
  end if;
  select array_agg(mv.lote_id) into v_lotes
  from movimientos mv join operaciones o on o.id = mv.operacion_id
  where o.entrega_id = p_entrega and o.tipo = 'devolucion_kit';
  delete from operaciones where entrega_id = p_entrega and tipo = 'devolucion_kit';
  update entrega_items set devuelto = null, descartado = null where entrega_id = p_entrega;
  update entregas set estado = 'entregado', fecha_devolucion = null, recibido_por = null, nota_devolucion = null
  where id = p_entrega;
  perform _verificar_lotes(coalesce(v_lotes, '{}'));
end $$;

-- Anula una entrega no devuelta: todo vuelve al stock como si no hubiera salido
create or replace function anular_entrega(p_entrega bigint) returns void
language plpgsql as $$
begin
  if not exists (select 1 from entregas where id = p_entrega) then raise exception 'Entrega no encontrada'; end if;
  if exists (select 1 from entregas where id = p_entrega and estado = 'devuelto') then
    raise exception 'Primero revierte la devolución de este kit';
  end if;
  delete from entregas where id = p_entrega;
end $$;

-- ------------------------------------------------------------ configuración
create or replace function guardar_config(p_clave text, p_valor text) returns void
language sql as $$
  insert into configuracion (clave, valor) values (p_clave, p_valor)
  on conflict (clave) do update set valor = excluded.valor
$$;

